import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../src/i18n');
const localeDir = join(root, 'locales');
const generatedDir = join(localeDir, 'compact');
const check = process.argv.includes('--check');
const isRecord = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === 'object' && !Array.isArray(value);

async function load(name: string): Promise<Record<string, unknown>> {
  return (await import(pathToFileURL(join(localeDir, name)).href)).default;
}

const names = (await readdir(localeDir))
  .filter((name) => name.endsWith('.ts') && name !== 'en-US.ts')
  .sort();
const english = await load('en-US.ts');
const dictionaries = await Promise.all(names.map(load));

// Generated object literals cannot faithfully represent custom prototypes,
// accessors, shared references or an own __proto__ key. Refuse them before
// writing anything instead of silently changing the original dictionary.
function assertSafeValue(value: unknown, path: string, seen: WeakSet<object>): void {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return;
  if (typeof value === 'number' && Number.isFinite(value) && !Object.is(value, -0)) return;
  if (typeof value !== 'object') throw new Error(`Unsupported locale value at ${path}`);
  if (seen.has(value)) throw new Error(`Shared or cyclic locale object at ${path}`);
  seen.add(value);

  const array = Array.isArray(value);
  if (Object.getPrototypeOf(value) !== (array ? Array.prototype : Object.prototype)) {
    throw new Error(`Unsupported locale object prototype at ${path}`);
  }
  const keys = Reflect.ownKeys(value);
  if (array && (keys.length !== value.length + 1 || !keys.includes('length'))) {
    throw new Error(`Unsupported sparse or extended locale array at ${path}`);
  }
  if (array) {
    for (let index = 0; index < value.length; index++) {
      if (!Object.hasOwn(value, index)) {
        throw new Error(`Unsupported sparse or extended locale array at ${path}`);
      }
    }
  }
  for (const key of keys) {
    if (array && key === 'length') continue;
    if (typeof key !== 'string') throw new Error(`Unsupported locale symbol at ${path}`);
    if (key === '__proto__') throw new Error(`Unsupported __proto__ locale key at ${path}`);
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (
      !descriptor?.enumerable ||
      !descriptor.writable ||
      !descriptor.configurable ||
      !('value' in descriptor)
    ) {
      throw new Error(`Unsupported locale property at ${path}.${key}`);
    }
    assertSafeValue(descriptor.value, `${path}.${key}`, seen);
  }
}
assertSafeValue(english, 'en-US.ts', new WeakSet());
for (let index = 0; index < names.length; index++) {
  assertSafeValue(dictionaries[index], names[index], new WeakSet());
}

const counts = new Map<string, number>();
function count(value: unknown, reference: unknown): void {
  if (typeof value === 'string' && value === reference) {
    counts.set(value, (counts.get(value) ?? 0) + 1);
  } else if (isRecord(value)) {
    for (const [key, child] of Object.entries(value)) {
      count(child, isRecord(reference) ? reference[key] : undefined);
    }
  }
}
for (const dict of dictionaries) count(dict, english);

// Only share frequently repeated values: short-lived references otherwise add
// more bytes to the language chunk and the common table than they remove.
const shared = [...counts]
  .filter(([, count]) => count >= 5)
  .sort(([a, an], [b, bn]) => bn - an || (a < b ? -1 : a > b ? 1 : 0))
  .map(([value]) => value);
const positions = new Map(shared.map((value, index) => [value, index]));
function encode(value: unknown, reference: unknown): unknown {
  if (typeof value === 'string' && value === reference && positions.has(value)) {
    return [positions.get(value)];
  }
  if (Array.isArray(value)) return [-1, value];
  if (isRecord(value)) {
    return Object.fromEntries(
      Object.entries(value).map(([key, child]) => [
        key,
        encode(child, isRecord(reference) ? reference[key] : undefined),
      ]),
    );
  }
  return value;
}

const outputs = new Map<string, string>();
const header = '// Generated by scripts/generateCompactLocales.ts; do not edit.\n';
outputs.set(
  join(root, 'compactLocaleValues.generated.ts'),
  `${header}export default ${JSON.stringify(shared)} as const;\n`,
);
for (let i = 0; i < names.length; i++) {
  const name = names[i].replace(/\.ts$/, '.generated.ts');
  const data = JSON.stringify(encode(dictionaries[i], english));
  outputs.set(
    join(generatedDir, name),
    `${header}import { restoreCompactLocale } from '../../compactLocale';\nimport type { LocaleDict } from '../../index';\nexport default restoreCompactLocale(${data}) as LocaleDict;\n`,
  );
}
if (check) {
  const found = (await readdir(generatedDir))
    .filter((name) => name.endsWith('.generated.ts'))
    .sort();
  const expected = names.map((name) => name.replace(/\.ts$/, '.generated.ts'));
  if (JSON.stringify(found) !== JSON.stringify(expected))
    throw new Error('Compact locale files differ from sources');
  for (const [path, contents] of outputs) {
    if ((await readFile(path, 'utf8')) !== contents)
      throw new Error(`Stale compact locale: ${path}`);
  }
} else {
  await mkdir(generatedDir, { recursive: true });
  for (const [path, contents] of outputs) await writeFile(path, contents);
}
console.log(
  `${check ? 'Verified' : 'Generated'} ${names.length} compact locales and ${shared.length} shared values.`,
);
