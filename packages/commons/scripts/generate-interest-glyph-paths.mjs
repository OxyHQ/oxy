#!/usr/bin/env node
/**
 * Generates `constants/interestTagGlyphs.generated.ts` from Bloom's own glyphs.
 *
 * ## Why this exists
 *
 * `components/auth/InterestTagsCanvas.tsx` draws its tag icons INSIDE a Skia
 * canvas, and Skia cannot render a React component. The canvas used to solve
 * that by drawing MaterialCommunityIcons CODEPOINTS as text from
 * `@expo/vector-icons`' TTF — which meant the app shipped that font: 1,307,660
 * bytes, 42% of its 3.0 MB of iOS assets, measured in `expo export`, for
 * fifteen glyphs on one onboarding screen.
 *
 * Bloom's Remix glyphs are single SVG paths (`createSinglePathSVG({ path })`),
 * and Skia draws an SVG path natively. So the canvas can use the SAME artwork as
 * the rest of the app with no font at all — it just needs the path STRING, which
 * a React component does not expose at runtime.
 *
 * This script reads those strings out of the installed Bloom and writes them to
 * a generated module. It is the same shape `@oxy.so/services` uses for its icon
 * font subsets (`scripts/generate-icon-font-subsets.mjs`): a derived artifact
 * with the generator committed beside it, so the data is never hand-copied and
 * can always be rebuilt from its source of truth.
 *
 * Run it after changing `INTEREST_TAGS` or bumping Bloom:
 *
 *     node scripts/generate-interest-glyph-paths.mjs          # write
 *     node scripts/generate-interest-glyph-paths.mjs --check  # verify, for CI
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'constants', 'interestTagGlyphs.generated.ts');

/**
 * Tag id -> the Bloom glyph that names it.
 *
 * Kept HERE rather than in `constants/interestTags.ts` so the tag list stays
 * pure data and this file owns everything about how a tag is drawn.
 */
const GLYPHS = {
  code: 'RiCodeSLine',
  design: 'RiPaintBrushLine',
  music: 'RiMusic2Line',
  travel: 'RiFlightTakeoffLine',
  finance: 'RiWallet3Line',
  cook: 'RiRestaurantLine',
  meditate: 'RiLeafLine',
  work: 'RiComputerLine',
  learn: 'RiBookOpenLine',
  exercise: 'RiWalkLine',
  photo: 'RiCameraLine',
  garden: 'RiPlantLine',
  explore: 'RiCompass3Line',
  write: 'RiQuillPenLine',
  research: 'RiFlaskLine',
};

const bloomRoot = dirname(require.resolve('@oxy.so/bloom/package.json'));

function pathFor(name) {
  const file = join(bloomRoot, 'src', 'icons', 'remix', `${name}.tsx`);
  const source = readFileSync(file, 'utf8');
  const match = /path:\s*'([^']+)'/.exec(source);
  if (!match) throw new Error(`No single-path SVG found in ${file}. Did Bloom change its icon template?`);
  return match[1];
}

const version = require('@oxy.so/bloom/package.json').version;
const entries = Object.entries(GLYPHS)
  .map(([id, glyph]) => `  /** Bloom \`${glyph}\`. */\n  ${id}: '${pathFor(glyph)}',`)
  .join('\n');

const banner = `/**
 * GENERATED by \`scripts/generate-interest-glyph-paths.mjs\` — do not edit.
 *
 * The SVG path of each interest tag's Bloom glyph, read out of
 * \`@oxy.so/bloom@${version}\`. \`InterestTagsCanvas\` draws these with Skia,
 * because Skia cannot render a React component and this is how the canvas uses
 * the SAME artwork as the rest of the app instead of shipping an icon font.
 *
 * Every path is in Remix's 24x24 viewBox; the canvas scales from there.
 */
`;

const output = `${banner}export const INTEREST_TAG_GLYPH_PATHS: Record<string, string> = {
${entries}
};

/** The viewBox every path above is drawn in. */
export const INTEREST_TAG_GLYPH_VIEWBOX = 24;
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== output) {
    console.error(`${OUT} is stale. Run: node scripts/generate-interest-glyph-paths.mjs`);
    process.exit(1);
  }
  console.log('interest tag glyph paths are up to date');
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${OUT} (${Object.keys(GLYPHS).length} glyphs from @oxy.so/bloom@${version})`);
}
